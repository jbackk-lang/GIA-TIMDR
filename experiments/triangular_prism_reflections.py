"""Exact reflection group of a regular triangular prism with square sides.

The prism has equilateral triangular ends and three square lateral faces.
Set side length and height to 1. Exact arithmetic uses SymPy and sqrt(3).
Face order: bottom, top, and three vertical side planes.
"""
import sympy as s
from itertools import combinations
from collections import Counter

r3 = s.sqrt(3)
I = s.eye(3)
z = s.Integer(0)
h = s.Integer(1)

# Equilateral triangle in xy-plane; its three side lines are:
# x = 0, sqrt(3)*x + y = sqrt(3), sqrt(3)*x - y = sqrt(3).
# Each lateral face is the vertical plane above one side.
planes = [
    (s.Matrix([0, 0, 1]), 0),       # bottom: z=0
    (s.Matrix([0, 0, 1]), h),       # top: z=1
    (s.Matrix([1, 0, 0]), 0),       # side 1: x=0
    (s.Matrix([r3, 1, 0]), r3),     # side 2
    (s.Matrix([r3, -1, 0]), r3),    # side 3
]

def reflection(n, c):
    n = s.Matrix(n)
    M = s.simplify(I - 2 * (n * n.T) / (n.dot(n)))
    b = s.simplify(2 * c * n / n.dot(n))
    return M, b

def compose(A, B):
    """A after B, each affine map represented by (M,b)."""
    M, b = A
    N, d = B
    return (s.simplify(M*N), s.simplify(M*d+b))

def key(T):
    M, b = T
    return tuple(M) + tuple(b)

def kind(T):
    M, b = T
    if M == I:
        return "identity" if b == s.zeros(3, 1) else "translation"
    # An orthogonal matrix with determinant +1 is rotation or screw;
    # det -1 is a reflection/glide-reflection type.
    det = s.simplify(M.det())
    if det == 1:
        # Rotation axis direction is the nullspace of M-I.
        ns = (M-I).nullspace()
        if ns:
            u = ns[0]
            return "screw" if s.simplify(u.dot(b)) != 0 else "rotation"
    return "orientation_reversing"

def main():
    G = [reflection(n, c) for n, c in planes]
    for S in G:
        assert compose(S, S)[0] == I
        assert compose(S, S)[1] == s.zeros(3, 1)

    pair_types = Counter()
    pair_rotation_angles = Counter()
    for i, j in combinations(range(5), 2):
        T = compose(G[i], G[j])
        k = kind(T)
        pair_types[k] += 1
        M, _ = T
        if k == "rotation":
            cosine = s.simplify((s.trace(M)-1)/2)
            pair_rotation_angles[str(cosine)] += 1

    assert pair_types == Counter({"rotation": 9, "translation": 1}), pair_types
    assert pair_rotation_angles == Counter({"-1": 6, "-1/2": 3}), pair_rotation_angles

    # Reduced words: no adjacent repetition. Count distinct exact affine maps.
    layer = [((), (I, s.zeros(3, 1)))]
    stats = {}
    for length in range(1, 9):
        nxt = []
        unique = {}
        for word, T in layer:
            for i, gen in enumerate(G):
                if word and word[-1] == i:
                    continue
                nw = word + (i,)
                nt = compose(gen, T)
                nxt.append((nw, nt))
                unique.setdefault(key(nt), nt)
        stats[length] = (len(nxt), len(unique))
        layer = nxt

    # The group is the direct product of D3 (six planar symmetries)
    # and the infinite dihedral group generated by z=0 and z=1.
    # Reduced words of length <=8 have these exact distinct-map counts.
    expected = {
        1: (5, 5), 2: (20, 19), 3: (80, 47), 4: (320, 69),
        5: (1280, 91), 6: (5120, 113), 7: (20480, 135),
        8: (81920, 157),
    }
    assert stats == expected, stats

    print("PASS: exact regular triangular prism reflection experiment.")
    print("faces=5 (2 equilateral triangles + 3 squares)")
    print(f"pair_products={dict(pair_types)}")
    print(f"rotation_cosines={dict(pair_rotation_angles)}")
    print("side-side products: 3 rotations by 120 degrees (order 3)")
    print("end-side products: 6 half-turns (order 2)")
    print("end-end product: translation by 2 units along prism axis")
    for n, (words, distinct) in stats.items():
        print(f"length_{n}: reduced_words={words}; distinct_affine_maps={distinct}; collisions={words-distinct}")
    print("GROUP: D3 x D_infinity; no screw motions; no nonzero-pitch resonances.")
    print("LIMIT: this is the ideal regular prism; unequal height changes square faces to rectangles, not the plane group.")

if __name__ == "__main__":
    main()
